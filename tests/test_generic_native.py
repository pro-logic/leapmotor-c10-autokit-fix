"""Source-only public native generation refusal and contract-boundary tests."""
import copy
import json
import unittest
from unittest.mock import patch

from generic_analysis import analyze_driver
from generic_native import (DEFAULT_PROFILE, _entry_contract, checked_profile,
                            generate_native, recognized_native, validate_native)
from tests.test_generic import native_fixture


class NativeGenerationTests(unittest.TestCase):
    def test_profile_is_explicit_and_cannot_silently_change_native_behavior(self):
        self.assertEqual(checked_profile(), DEFAULT_PROFILE)
        changed = checked_profile()
        changed['raw_open'][1] = 1234
        self.assertEqual(checked_profile()['raw_open'], [2560, 1440])
        for key, value in (('raw_open', [1920, 1080]), ('effective_open', [2560, 1440]),
                           ('aa_content', [1280, 720]), ('aa_dpi', 232), ('calibration', ''),
                           ('aa_touch', dict(integer_range=[0,10000], subtract_y=501, clamp_min=0))):
            candidate = copy.deepcopy(DEFAULT_PROFILE)
            candidate[key] = value
            with self.subTest(key=key), self.assertRaisesRegex(ValueError, 'Unsupported vehicle profile'):
                generate_native(b'bad input', profile=candidate)

    def test_missing_ambiguous_and_incomplete_native_layouts_refuse(self):
        for source in (b'', b'not an ELF', native_fixture(invalid_length=True),
                       native_fixture(duplicate=True), native_fixture(divisor=1000), native_fixture()):
            with self.subTest(size=len(source)), self.assertRaises(ValueError):
                generate_native(source)

    def test_supplied_analysis_is_recomputed_rather_than_trusted(self):
        source = native_fixture()
        native = analyze_driver(source)
        for key, value in (('sha256', '0' * 64), ('unique_candidates', False), ('entry', 0)):
            changed = copy.deepcopy(native)
            changed[key] = value
            with self.subTest(key=key), self.assertRaisesRegex(ValueError, 'analysis is stale, edited'):
                recognized_native(source, changed)
        changed = copy.deepcopy(native)
        changed['open_candidates'][0]['hook']['original_bytes'] = '00000000'
        with self.assertRaisesRegex(ValueError, 'analysis is stale, edited'):
            recognized_native(source, changed)

    def test_output_and_manifest_tampering_fail_before_independent_validation(self):
        manifest = dict(profile=checked_profile(), source_sha256='identity', generation_allowed=True)
        with patch('generic_native.recognized_native', return_value={}), \
             patch('generic_native._production_materialize', return_value=(b'expected generated bytes', manifest)):
            for body, receipt in ((b'corrupted', manifest),
                                  (b'expected generated bytes', dict(manifest, generation_allowed=False)),
                                  (b'expected generated bytes', dict(manifest, source_sha256='another input'))):
                with self.subTest(body=body), self.assertRaisesRegex(ValueError, 'bytes or manifest differ'):
                    validate_native(b'source', body, receipt)

    def test_entry_gate_retains_numeric_data_but_refuses_protected_code_references(self):
        manifest = dict(hooks=[dict(va=0x10100)], layout=dict(rx_va=0x11000), code_bytes=400)
        def audit(direct=(), absolute=(), constructors=()):
            return dict(direct=dict(hits=list(direct)), absolute=dict(hits=list(absolute)),
                        constructors=dict(hits=list(constructors), partial_movt_constructors=[]))
        data = dict(source_va=0x10900, source_sections=[dict(name='.rodata', declared_code=False)],
                    protected_spans=['new-rx'])
        with patch('generic_native._entry_inventory_json', return_value=json.dumps(audit([data]))):
            result = _entry_contract(native_fixture(), manifest)
            self.assertFalse(result['complete_indirect_target_proof'])
            self.assertEqual(len(result['inventory']['direct']['hits']), 1)
        for value in (audit([dict(data, protected_spans=['hook-0-interior'])]),
                      audit([dict(data, source_sections=[dict(name='.text', declared_code=True)])]),
                      audit(absolute=[dict(protected_spans=['hook-0-interior'])]),
                      audit(constructors=[dict(protected_spans=['new-rx'])])):
            with patch('generic_native._entry_inventory_json', return_value=json.dumps(value)), self.assertRaises(ValueError):
                _entry_contract(native_fixture(), manifest)


if __name__ == '__main__':
    unittest.main()
